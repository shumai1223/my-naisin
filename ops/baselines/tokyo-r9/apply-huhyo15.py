# 別表4付表(R9・n2_15相当=20260916_r9_15・1頁・数値は画像のみでテキスト層なし→220dpi画像から転記): 推薦実施校のうち観点別学習状況の評価で調査書を得点化する7校(エンカレッジスクール6+大田桜台)の
# 『観点別評価の得点(A/B/C)』『得点満点』『重視している教科や観点』を tokyo.ts の各校の『推薦に基づく選抜』レコードのnoteへ追記する(1回だけ実行)。得点満点=各観点のA得点の合計で全7校とも検算済み(243/400/270/180/282/228/325)。
import re
p = 'src/data/school-selection-methods/tokyo.ts'
s = open(p, encoding='utf8', newline='').read()
HEAD = '観点別学習状況の評価の得点化(別表4付表): 9教科(国語・社会・数学・理科・音楽・美術・保健体育・技術・家庭・外国語[英語])×観点Ⅰ知識・技能/Ⅱ思考・判断・表現/Ⅲ主体的に学習に取り組む態度の27区分について、評価A・B・Cに応じて得点化する。'
ROWS = [
  ('蒲田', '普通科(エンカレッジスクール)', '全教科・全観点でA=9・B=6・C=3', 243, '全教科・全観点'),
  ('足立東', '普通科(エンカレッジスクール)', '国語・社会・数学・理科・外国語はⅠ・ⅡがA=13・B=10・C=1、ⅢがA=18・B=13・C=1。音楽・美術・保健体育・技術・家庭はⅠ・ⅡがA=13・B=10・C=1、ⅢがA=19・B=13・C=1', 400, '観点Ⅲ(全教科)'),
  ('東村山', '普通科(エンカレッジスクール)', '全教科・全観点でA=10・B=6・C=1', 270, '全教科・全観点'),
  ('秋留台', '普通科(エンカレッジスクール)', '全教科でⅠ・ⅡがA=5・B=3・C=1、ⅢがA=10・B=5・C=1', 180, '観点Ⅲ(全教科)'),
  ('中野工科', '食品サイエンス', '理科・技術・家庭は全観点でA=12・B=7・C=1。その他の教科はⅠ・ⅡがA=9・B=5・C=1、ⅢがA=12・B=7・C=1', 282, '教科(理、技家)、観点Ⅲ(国、社、数、音、美、保体、外国語[英語])'),
  ('練馬工科', 'キャリア技術', '美術・技術・家庭は全観点でA=10・B=7・C=1。その他の教科はⅠ・ⅡがA=7・B=5・C=1、ⅢがA=10・B=7・C=1', 228, '教科(美、技家)、観点Ⅲ(国、社、数、理、音、保体、外国語[英語])'),
  ('大田桜台', 'ビジネスコミュニケーション', '国語はⅠ・ⅡがA=15・B=10・C=1、ⅢがA=25・B=12・C=1。社会はⅠ・ⅡがA=12・B=8・C=1、ⅢがA=21・B=10・C=1。外国語はⅠ・ⅡがA=20・B=10・C=1、ⅢがA=35・B=14・C=1。数学・理科・音楽・美術・保健体育・技術・家庭はⅠ・ⅡがA=6・B=4・C=1、ⅢがA=13・B=7・C=1', 325, '教科(国・社・英)、全教科の観点Ⅲ(主体的に学習に取り組む態度)'),
]
n = 0
for school, dept, rule, total, heavy in ROWS:
    pat = re.compile(r"(      schoolName: '" + re.escape(school) + r"',\r?\n      department: '" + re.escape(dept) + r"[^']*',\r?\n      selectionCategory: '推薦に基づく選抜',\r?\n(?:      [^\n]*\n)*?      note: ')([^']*)(',)")
    m = pat.search(s)
    assert m, school
    if '別表4付表' in m.group(2): raise SystemExit('既に適用済み ' + school)
    add = '。' + HEAD + school + 'の得点: ' + rule + '。得点満点' + str(total) + '点(各観点のAの得点の合計)。重視している教科や観点: ' + heavy
    s = s[:m.start(2)] + m.group(2) + add + s[m.end(2):]
    n += 1
open(p, 'w', encoding='utf8', newline='').write(s)
print('patched', n)
