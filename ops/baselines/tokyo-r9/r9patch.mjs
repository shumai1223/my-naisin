export function buildR9() {
  const base = loadR8().map((r) => ({ ...r }));
  const out = [];
  base.forEach((r, i) => {
    P.filter((p) => p.op === 'ins' && p.i === i).forEach((p) => out.push({ ...p.row }));
    if (P.some((p) => p.op === 'del' && p.i === i)) return;
    const s = P.filter((p) => p.op === 'set' && p.i === i);
    s.forEach((p) => Object.assign(r, p.row));
    out.push(r);
  });
  P.filter((p) => p.op === 'ins' && p.i >= base.length).forEach((p) => out.push({ ...p.row }));
  return out;
}
