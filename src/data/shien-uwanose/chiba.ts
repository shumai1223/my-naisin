// 授業料が国の支給上限額(457,200円)を上回る高校に通う生徒に対して、就学支援金と合わせて
// 授業料相当額を全額支給する措置が、新入生の卒業見込み年度である令和10年度まで継続される。
// ★この経過措置による上乗せ額は「実際の授業料と国上限額(457,200円)との差額」であり、学校ごとの
