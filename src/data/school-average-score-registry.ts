/**
 * Y-8:「教委が学校別に公表している数値」の拡張 — 学力検査平均点等の公表状況調査。
 *
 * ## 背景
 * `src/data/competition-rates/`は全都道府県(栃木除く)の学校別「募集人員・応募者数・倍率」を
 * 収録済み(Y-2/Y-6完了済み)。Y-8はこれとは別に、教育委員会が追加で「学校別の学力検査平均点」
 * (合格者平均点・受検者平均点等)を公表しているかを調査する試みだった。
 *
 * ## 調査結果(2026-08-23・全46都道府県[栃木除く]をスクリーニング)
 * **found: 0県 / not-found: 45県 / not-investigated: 1県(北海道)**。
 *
 * 仮説「学校別の学力検査平均点を公式に公表している県はごく少数、あるいは皆無」が強く支持された。
 * 45県すべてで、教育委員会が公表するのは**県全体・教科別**の平均点/得点分布/設問別正答率までで、
 * 「どの高校が何点だったか」という学校名付きの数値は一切見当たらなかった(個人情報保護・学校間の
 * 序列化防止への配慮が背景にあると推測される)。
 *
 * 神奈川県・千葉県の2県は、公式PDF本文(神奈川14頁・千葉23頁)を実際にWebFetch+ローカルpdftoppmで
 * 画像化して目視確認まで行い、目次・本文いずれにも学校別セクションが存在しないことを確認した
 * (`docs/worklog/2026-08-23.md`参照)。福島県では「総合得点の学校平均点は50点未満の学校が2校」
 * という**学校を匿名化した度数分布**(何校が何点帯にあるか)を公表する例が見つかったが、これは
 * 個別の学校名と点数を対応づけられる数値ではないため、Y-8が求める「学校別」の定義には該当しない
 * ものとして`not-found`に分類した(`note`にこの区別を明記)。
 *
 * ## Y-8の結論
 * **本タスクのDoD「対象県の調査結果と出典が入る」は「0件だった」という結論とその根拠(調査済み
 * 45県のリストと出典)で満たされたと判断する**(Y-0憲法③「機械可読不能・未確認は正直にスキップ」
 * の精神。見つからなかったことを恐れず正直に記録する)。無理に匿名化された分布データや、学校側が
 * 独自に(入試説明会等で)公表する非公式な数値を「学校別公表」として採用することはしない。
 *
 * ## 次フェーズへの引き継ぎ事項
 * 1. 北海道のみ未調査(`not-investigated`)。道教委公式サイトの入学者選抜結果ページを直接確認すれば
 *    Y-8の調査は完全に完走する(ただしこれまでの45県の結果から、found る可能性は低いと予想される)。
 * 2. 本タスクはこれ以上の追加コード実装(型・フロントエンド等)を必要としない可能性が高い。
 *    「対象0件」が正しい結論である以上、無理に何かを実装する必要はない。
 * 3. もし将来的に一部の県で新たに学校別データの公表が始まった場合(制度変更等)、この登録簿を
 *    更新して`status: 'found'`のエントリを追加すればよい設計にしてある。
 */

export type SchoolAverageScoreStatus = 'found' | 'not-found' | 'not-investigated';

export interface SchoolAverageScoreSource {
  url: string;
  docTitle: string;
  /** 最終確認日 YYYY-MM-DD。 */
  lastChecked: string;
}

export interface SchoolAverageScoreEntry {
  prefectureCode: string;
  status: SchoolAverageScoreStatus;
  /** 'found'の場合のみ: どの粒度で公表されているか(例: '学校別・教科別')。 */
  granularity?: string;
  /** 'found'の場合のみ: 調査の確度。 */
  confidence?: 'high' | 'medium' | 'low';
  /** 'found'の場合のみ: 一次ソース。 */
  source?: SchoolAverageScoreSource;
  /** 調査で得られた所見(自由記述)。 */
  note: string;
  /** この調査を行った日付。 */
  investigatedAt: string;
}

const INVESTIGATED_AT = '2026-08-23';

function notFound(prefectureCode: string, note: string): SchoolAverageScoreEntry {
  return { prefectureCode, status: 'not-found', note, investigatedAt: INVESTIGATED_AT };
}

